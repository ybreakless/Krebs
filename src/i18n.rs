//! Internationalization for Krebs Studio.
//!
//! Provides a 10-language UI translation layer plus a bidirectional-text
//! helper. The application language is persisted in
//! `./krebs_data/config.toml` as `language = "en"` and every user-facing
//! string in the toolbar, dialogs, whiteboard tools, and onboarding tour is
//! served through [`t`].
//!
//! # Layout mirroring
//!
//! Persian (`fa`) and Arabic (`ar`) are right-to-left scripts. Use [`is_rtl`]
//! to flip horizontal alignment and drawer placement while bidirectional
//! text inside a paragraph is shaped correctly by HarfBuzz/Swash and word
//! separation stays controllable through the ZWNJ shortcut (`Shift+Space`).
//!
//! # AI prompt language
//!
//! Model-facing prompt templates intentionally remain English so every
//! provider (local Hermes, Claude, ChatGPT, DeepSeek) receives the same
//! canonical instruction text. Only UI labels are localized.

/// Every supported UI language, ordered by [`Lang::ALL`].
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum Lang {
    En,
    De,
    Fa,
    Ru,
    Zh,
    Ja,
    Ko,
    Ar,
    Fr,
    Es,
}

impl Lang {
    /// All languages in canonical order; indices define translation arrays.
    pub const ALL: [Lang; 10] = [
        Lang::En,
        Lang::De,
        Lang::Fa,
        Lang::Ru,
        Lang::Zh,
        Lang::Ja,
        Lang::Ko,
        Lang::Ar,
        Lang::Fr,
        Lang::Es,
    ];

    /// ISO 639-1 code as persisted in `config.toml`.
    #[must_use]
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::De => "de",
            Lang::Fa => "fa",
            Lang::Ru => "ru",
            Lang::Zh => "zh",
            Lang::Ja => "ja",
            Lang::Ko => "ko",
            Lang::Ar => "ar",
            Lang::Fr => "fr",
            Lang::Es => "es",
        }
    }

    /// Language autonym shown in the selector (never translated).
    #[must_use]
    pub fn display(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::De => "Deutsch",
            Lang::Fa => "فارسی",
            Lang::Ru => "Русский",
            Lang::Zh => "中文（简体）",
            Lang::Ja => "日本語",
            Lang::Ko => "한국어",
            Lang::Ar => "العربية",
            Lang::Fr => "Français",
            Lang::Es => "Español",
        }
    }

    /// Parses a persisted config code, falling back to English.
    #[must_use]
    pub fn from_code(code: &str) -> Lang {
        Lang::ALL
            .iter()
            .copied()
            .find(|l| l.code().eq_ignore_ascii_case(code))
            .unwrap_or(Lang::En)
    }
}

/// Returns `true` for right-to-left scripts that require mirrored UI layout.
///
/// # Examples
/// ```
/// # use crate::i18n::is_rtl;
/// assert!(is_rtl("fa"));
/// assert!(is_rtl("ar"));
/// assert!(!is_rtl("de"));
/// ```
#[must_use]
pub fn is_rtl(lang: &str) -> bool {
    matches!(lang, "fa" | "ar")
}

