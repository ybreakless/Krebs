/// Formats the tour step counter in the active language.
#[must_use]
pub fn step_counter(lang: Lang, step: usize, total: usize) -> String {
    STEP_OF[lang as usize]
        .replace("{0}", &step.to_string())
        .replace("{1}", &total.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn enum_indices_align_with_all() {
        assert_eq!(Lang::En as usize, 0);
        Lang::ALL
            .iter()
            .enumerate()
            .for_each(|(i, _)| assert_eq!(i, Lang::ALL[i] as usize));
    }

    #[test]
    fn rtl_detection() {
        assert!(is_rtl("fa"));
        assert!(is_rtl("ar"));
        assert!(!is_rtl("en"));
        assert!(!is_rtl("de"));
        assert!(!is_rtl("zh"));
        assert!(!is_rtl("he")); // not supported yet, but not RTL here
    }

    #[test]
    fn every_language_translates_every_key_sample() {
        for l in Lang::ALL {
            for k in [
                Key::Write,
                Key::Whiteboard,
                Key::Preview,
                Key::WipeBoard,
                Key::TourGetStarted,
                Key::NothingToPreview,
                Key::SecWorkspace,
            ] {
                assert!(!t(l, k).trim().is_empty(), "missing {l:?} for {k:?}");
            }
        }
    }

    #[test]
    fn from_code_roundtrip_and_fallback() {
        for l in Lang::ALL {
            assert_eq!(Lang::from_code(l.code()), l);
        }
        assert_eq!(Lang::from_code("DE"), Lang::De);
        assert_eq!(Lang::from_code("xx-unknown"), Lang::En);
    }

    #[test]
    fn step_counter_formats() {
        assert_eq!(step_counter(Lang::En, 3, 5), "Step 3 of 5");
        assert_eq!(step_counter(Lang::De, 2, 7), "Schritt 2 von 7");
        assert_eq!(step_counter(Lang::Fa, 1, 7), "مرحلهٔ 1 از 7");
    }
}
